import React, { useState } from 'react';
import { ToolItem } from '../../types';
import { Search, Eye, FileSpreadsheet, Bot, Code, DollarSign, Copy, CheckCircle2, Globe, Shield, HelpCircle } from 'lucide-react';

interface Props {
  tool: ToolItem;
}

export const SeoToolRunner: React.FC<Props> = ({ tool }) => {
  // Meta Tag & SERP States
  const [metaTitle, setMetaTitle] = useState('AITools Hub - 100+ Free Online AI & Utility Tools');
  const [metaDescription, setMetaDescription] = useState(
    'Convert PDFs, resize images, calculate mortgage EMIs, format JSON, and read daily trending AI news with our 100+ free online SEO utilities.'
  );
  const [siteUrl, setSiteUrl] = useState('https://aitoolshub.com');

  // AdSense Calculator States
  const [dailyPageviews, setDailyPageviews] = useState(25000);
  const [averageRpm, setAverageRpm] = useState(8.5);

  // XML Sitemap State
  const [sitemapUrls, setSitemapUrls] = useState([
    'https://aitoolshub.com/',
    'https://aitoolshub.com/category/pdf',
    'https://aitoolshub.com/category/image',
    'https://aitoolshub.com/category/calculator',
    'https://aitoolshub.com/category/ai-text',
    'https://aitoolshub.com/category/code',
    'https://aitoolshub.com/category/seo',
    'https://aitoolshub.com/blog',
  ]);

  // Schema State
  const [schemaType, setSchemaType] = useState('SoftwareApplication');

  // Outputs
  const [generatedSeoCode, setGeneratedSeoCode] = useState<string>('');

  const calculateAdSenseEarnings = () => {
    const monthlyViews = dailyPageviews * 30;
    const monthlyEarnings = (monthlyViews / 1000) * averageRpm;
    const yearlyEarnings = monthlyEarnings * 12;
    return {
      monthly: Math.round(monthlyEarnings),
      yearly: Math.round(yearlyEarnings),
    };
  };

  const handleRunSeoTool = () => {
    if (tool.id === 'xml-sitemap-generator') {
      const xml = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${sitemapUrls
        .map(
          (u) =>
            `  <url>\n    <loc>${u}</loc>\n    <lastmod>${new Date().toISOString().split('T')[0]}</lastmod>\n    <changefreq>daily</changefreq>\n    <priority>0.8</priority>\n  </url>`
        )
        .join('\n')}\n</urlset>`;
      setGeneratedSeoCode(xml);
    } else if (tool.id === 'robots-txt-generator') {
      const robots = `# Robots.txt generated by AI Tools Hub\nUser-agent: *\nAllow: /\n\n# Disallow private admin interfaces\nDisallow: /api/\nDisallow: /admin/\n\n# Sitemap Location\nSitemap: ${siteUrl}/sitemap.xml`;
      setGeneratedSeoCode(robots);
    } else if (tool.id === 'schema-jsonld-generator' || tool.id === 'faq-schema-builder') {
      const schemaJson = {
        '@context': 'https://schema.org',
        '@type': schemaType,
        name: metaTitle,
        description: metaDescription,
        url: siteUrl,
        applicationCategory: 'BrowserUtility',
        operatingSystem: 'All',
        offers: {
          '@type': 'Offer',
          price: '0',
          priceCurrency: 'USD',
        },
      };
      setGeneratedSeoCode(JSON.stringify(schemaJson, null, 2));
    } else if (tool.id === 'seo-meta-tag-generator' || tool.id === 'open-graph-generator') {
      const tags = `<!-- Primary Meta Tags -->\n<title>${metaTitle}</title>\n<meta name="title" content="${metaTitle}">\n<meta name="description" content="${metaDescription}">\n<link rel="canonical" href="${siteUrl}">\n\n<!-- Open Graph / Facebook -->\n<meta property="og:type" content="website">\n<meta property="og:url" content="${siteUrl}">\n<meta property="og:title" content="${metaTitle}">\n<meta property="og:description" content="${metaDescription}">\n\n<!-- Twitter -->\n<meta property="twitter:card" content="summary_large_image">\n<meta property="twitter:title" content="${metaTitle}">\n<meta property="twitter:description" content="${metaDescription}">`;
      setGeneratedSeoCode(tags);
    } else {
      setGeneratedSeoCode(`<!-- SEO Output Code -->\n<link rel="canonical" href="${siteUrl}">`);
    }
  };

  const earnings = calculateAdSenseEarnings();

  return (
    <div className="space-y-6">
      {/* 1. Meta Tag & SERP Preview */}
      {['seo-meta-tag-generator', 'open-graph-generator', 'canonical-url-generator'].includes(tool.id) && (
        <div className="space-y-4">
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <div>
              <label className="block text-xs font-semibold text-gray-700 dark:text-gray-300 mb-1">Website Title Tag</label>
              <input
                type="text"
                value={metaTitle}
                onChange={(e) => setMetaTitle(e.target.value)}
                className="w-full px-3 py-2 text-xs rounded-lg border border-gray-300 dark:border-gray-600 bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100"
              />
              <span className="text-[10px] text-gray-500">{metaTitle.length} / 60 Chars</span>
            </div>
            <div>
              <label className="block text-xs font-semibold text-gray-700 dark:text-gray-300 mb-1">Target Website URL</label>
              <input
                type="text"
                value={siteUrl}
                onChange={(e) => setSiteUrl(e.target.value)}
                className="w-full px-3 py-2 text-xs rounded-lg border border-gray-300 dark:border-gray-600 bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100"
              />
            </div>
          </div>
          <div>
            <label className="block text-xs font-semibold text-gray-700 dark:text-gray-300 mb-1">Meta Description</label>
            <textarea
              rows={3}
              value={metaDescription}
              onChange={(e) => setMetaDescription(e.target.value)}
              className="w-full p-3 text-xs rounded-lg border border-gray-300 dark:border-gray-600 bg-white dark:bg-gray-900 text-gray-900 dark:text-gray-100"
            ></textarea>
            <span className="text-[10px] text-gray-500">{metaDescription.length} / 160 Chars</span>
          </div>

          {/* Live SERP Snippet Preview */}
          <div className="bg-white dark:bg-gray-900 p-4 rounded-xl border border-gray-200 dark:border-gray-700 shadow-sm space-y-1">
            <span className="text-[10px] uppercase font-bold text-gray-400 tracking-wider">Live Google Search SERP Preview</span>
            <div className="flex items-center gap-1.5 text-xs text-emerald-700 dark:text-emerald-400 truncate">
              <Globe className="w-3.5 h-3.5" /> {siteUrl}
            </div>
            <h3 className="text-base font-semibold text-blue-700 dark:text-blue-400 hover:underline cursor-pointer truncate">
              {metaTitle}
            </h3>
            <p className="text-xs text-gray-600 dark:text-gray-300 line-clamp-2">{metaDescription}</p>
          </div>
        </div>
      )}

      {/* 2. Google AdSense Revenue Estimator */}
      {tool.id === 'adsense-revenue-calc' && (
        <div className="bg-white dark:bg-gray-900 rounded-xl p-6 border border-gray-200 dark:border-gray-700 space-y-5">
          <h4 className="text-sm font-bold text-gray-900 dark:text-gray-100 flex items-center gap-2">
            <DollarSign className="w-5 h-5 text-cyan-500" /> AdSense Earnings Estimator
          </h4>

          <div className="grid grid-cols-2 gap-4">
            <div>
              <label className="block text-xs font-semibold text-gray-700 dark:text-gray-300 mb-1">Daily Pageviews</label>
              <input
                type="number"
                value={dailyPageviews}
                onChange={(e) => setDailyPageviews(Number(e.target.value))}
                className="w-full px-3 py-2 text-sm font-bold rounded-lg border border-gray-300 dark:border-gray-600 bg-gray-50 dark:bg-gray-800 text-gray-900 dark:text-gray-100"
              />
            </div>
            <div>
              <label className="block text-xs font-semibold text-gray-700 dark:text-gray-300 mb-1">Target Page RPM ($)</label>
              <input
                type="number"
                step="0.5"
                value={averageRpm}
                onChange={(e) => setAverageRpm(Number(e.target.value))}
                className="w-full px-3 py-2 text-sm font-bold rounded-lg border border-gray-300 dark:border-gray-600 bg-gray-50 dark:bg-gray-800 text-gray-900 dark:text-gray-100"
              />
            </div>
          </div>

          <div className="grid grid-cols-2 gap-4 bg-cyan-50 dark:bg-cyan-950/40 p-5 rounded-xl border border-cyan-200 dark:border-cyan-800/80">
            <div>
              <p className="text-xs text-cyan-700 dark:text-cyan-400 font-medium">Est. Monthly Revenue</p>
              <p className="text-2xl font-black text-cyan-900 dark:text-cyan-100 mt-1">${earnings.monthly.toLocaleString()}</p>
            </div>
            <div>
              <p className="text-xs text-cyan-700 dark:text-cyan-400 font-medium">Est. Annual Revenue</p>
              <p className="text-2xl font-black text-cyan-900 dark:text-cyan-100 mt-1">${earnings.yearly.toLocaleString()}</p>
            </div>
          </div>
        </div>
      )}

      {/* Action Button */}
      <button
        onClick={handleRunSeoTool}
        className="w-full py-3 px-6 rounded-xl bg-gradient-to-r from-cyan-600 to-teal-600 hover:from-cyan-700 hover:to-teal-700 text-white font-semibold text-sm shadow-md shadow-cyan-500/20 flex items-center justify-center gap-2 transition-all cursor-pointer"
      >
        <Search className="w-4 h-4" /> Generate {tool.name} Output
      </button>

      {/* Code Output Area */}
      {generatedSeoCode && (
        <div className="bg-gray-950 rounded-xl p-5 border border-gray-800 shadow-md space-y-2">
          <div className="flex justify-between items-center text-xs text-gray-400">
            <span className="font-mono font-bold flex items-center gap-1 text-cyan-400">
              <Code className="w-4 h-4" /> SEO Code Result
            </span>
            <button
              onClick={() => {
                navigator.clipboard.writeText(generatedSeoCode);
                alert('SEO Code copied to clipboard!');
              }}
              className="hover:text-white flex items-center gap-1 font-semibold"
            >
              <Copy className="w-3.5 h-3.5" /> Copy Code
            </button>
          </div>
          <pre className="text-xs font-mono text-cyan-300/90 overflow-x-auto whitespace-pre-wrap leading-relaxed max-h-80 p-2">
            {generatedSeoCode}
          </pre>
        </div>
      )}
    </div>
  );
};
